import { ScoreItem } from './scoring';

export interface HistoryRecord {
  id: string;
  type: 'single' | 'compare';
  url: string;
  domain: string;
  customerName?: string;
  staffName?: string;
  score: number;
  timestamp: string; // ISO string
  scoreDiffFromPrevious?: number; // Điểm tăng/giảm so với lần trước
  items?: {
    id: string;
    ten: string;
    ketQua: 'dat' | 'nen_sua' | 'loi' | 'khong_ap_dung';
    diem: number;
    diemToiDa: number;
    ghiChu: string;
  }[];
  aiReview?: {
    strengths: string[];
    improvements: string[];
    isAutoGenerated?: boolean;
  };
  compareData?: {
    competitors: { url: string; domain: string; score: number }[];
    conclusions: string[];
    isAutoGenerated?: boolean;
  };
}

const STORAGE_KEY = 'ongnho_check_history';
const MAX_HISTORY_ITEMS = 20;

/**
 * Chuẩn hóa tên miền để coi abc.vn, www.abc.vn/, http://abc.vn là một
 */
export function normalizeDomain(url: string): string {
  if (!url) return '';
  let clean = url.trim().toLowerCase();
  clean = clean.replace(/^https?:\/\//i, '');
  clean = clean.replace(/^www\./i, '');
  // Bỏ path, query, hash để lấy domain gốc
  clean = clean.split('/')[0];
  clean = clean.split('?')[0];
  clean = clean.split('#')[0];
  return clean;
}

/**
 * Lấy danh sách lịch sử đã lưu
 */
export function getHistory(): HistoryRecord[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return [];
    const list = JSON.parse(raw);
    return Array.isArray(list) ? list : [];
  } catch {
    return [];
  }
}

/**
 * Tìm lần kiểm tra gần nhất trước đó của cùng một tên miền
 */
export function findPreviousCheck(domainOrUrl: string): HistoryRecord | null {
  const targetDomain = normalizeDomain(domainOrUrl);
  if (!targetDomain) return null;
  const history = getHistory();
  // Tìm mục gần nhất (đã được sắp xếp mới nhất ở đầu) có cùng domain
  const found = history.find((h) => h.type === 'single' && h.domain === targetDomain);
  return found || null;
}

/**
 * Lưu một lượt kiểm tra mới vào lịch sử
 */
export function saveHistoryRecord(
  record: Omit<HistoryRecord, 'id' | 'timestamp' | 'domain'>
): HistoryRecord {
  const history = getHistory();
  const domain = normalizeDomain(record.url);

  // Tính chênh lệch điểm so với lần trước của cùng domain
  let scoreDiff: number | undefined = undefined;
  if (record.type === 'single') {
    const prev = history.find((h) => h.type === 'single' && h.domain === domain);
    if (prev) {
      scoreDiff = record.score - prev.score;
    }
  }

  const newRecord: HistoryRecord = {
    ...record,
    id: `ongnho_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
    domain,
    timestamp: new Date().toISOString(),
    scoreDiffFromPrevious: scoreDiff,
  };

  // Thêm vào đầu danh sách, giới hạn 20 mục
  const updated = [newRecord, ...history].slice(0, MAX_HISTORY_ITEMS);
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    // Nếu quota bị vượt quá hoặc bị chặn trong private browsing, thử lưu 10 mục
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(updated.slice(0, 10)));
    } catch {
      console.warn('Bộ nhớ máy (localStorage) bị đầy hoặc bị chặn.');
    }
  }

  return newRecord;
}

/**
 * Xóa 1 mục khỏi lịch sử
 */
export function deleteHistoryItem(id: string): HistoryRecord[] {
  const history = getHistory().filter((item) => item.id !== id);
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(history));
  } catch (err) {
    console.error('Không thể cập nhật localStorage:', err);
  }
  return history;
}

/**
 * Xóa toàn bộ lịch sử
 */
export function clearAllHistory(): void {
  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch (err) {
    console.error('Không thể xóa localStorage:', err);
  }
}
