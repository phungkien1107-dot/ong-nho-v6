// Bảng màu chuẩn quy định
const COLORS = {
  yellow: '#FFB400',
  lightYellow: '#FFF3C4',
  darkBrown: '#2B1B0E',
  cream: '#FFFBF0',
  orange: '#E8890C',
  red: '#D64545',
  amber: '#E8A100',
  green: '#2E9E5B',
  grayText: '#78716C',
  border: '#E5E7EB',
  white: '#FFFFFF',
};

function getScoreColor(score: number): string {
  if (score >= 80) return COLORS.green;
  if (score >= 50) return COLORS.amber;
  return COLORS.red;
}

function getScoreLabel(score: number): string {
  if (score >= 80) return 'Rất tốt (Chuẩn SEO & Di động)';
  if (score >= 50) return 'Tạm ổn (Nên tối ưu thêm)';
  return 'Cần sửa chữa nhiều (Nhiều lỗi quan trọng)';
}

function getResultBadge(result: 'dat' | 'nen_sua' | 'loi' | 'khong_ap_dung', isNotApplicable?: boolean) {
  if (isNotApplicable || result === 'khong_ap_dung') {
    return {
      text: 'Không áp dụng',
      color: '#6B7280',
      bg: '#F3F4F6',
      border: '#D1D5DB',
    };
  }
  switch (result) {
    case 'dat':
      return {
        text: 'Đạt',
        color: '#2E9E5B',
        bg: '#EAF7EE',
        border: '#A7E3BE',
      };
    case 'nen_sua':
      return {
        text: 'Nên sửa',
        color: '#E8890C',
        bg: '#FFF7E6',
        border: '#FCD89C',
      };
    case 'loi':
    default:
      return {
        text: 'Lỗi',
        color: '#D64545',
        bg: '#FDF0F0',
        border: '#F8B4B4',
      };
  }
}

function formatKhongApDungGhiChu(ghiChu: string, ten: string): string {
  let clean = (ghiChu || '').trim();
  if (clean.toLowerCase().startsWith('không áp dụng:')) {
    clean = clean.slice('không áp dụng:'.length).trim();
  }
  if (clean.length > 0) {
    clean = clean.charAt(0).toLowerCase() + clean.slice(1);
  }
  if (clean.endsWith('.')) {
    clean = clean.slice(0, -1);
  }
  return `Không áp dụng: ${clean || ten.toLowerCase()}`;
}

