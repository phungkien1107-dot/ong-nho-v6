import React, { useState } from 'react';
import {
  ChevronDown,
  ChevronUp,
  Star,
  CheckCircle2,
  Search,
  Zap,
  FileText,
  Smartphone,
  ShieldCheck,
  Sparkles,
} from 'lucide-react';

interface RecommendationCategory {
  category: string;
  items: string[];
}

interface ComparisonPlanAccordionProps {
  topPriorities: string[];
  detailedRecommendations: RecommendationCategory[];
  isAutoGenerated?: boolean;
}

export function ComparisonPlanAccordion({
  topPriorities,
  detailedRecommendations,
  isAutoGenerated,
}: ComparisonPlanAccordionProps) {
  // Mặc định mở nhóm đầu tiên
  const [openSections, setOpenSections] = useState<Record<number, boolean>>({
    0: true,
    1: true,
  });

  const toggleSection = (idx: number) => {
    setOpenSections((prev) => ({
      ...prev,
      [idx]: !prev[idx],
    }));
  };

  const getCategoryIcon = (name: string) => {
    if (name.includes('SEO') || name.includes('Google')) return Search;
    if (name.includes('Tốc độ') || name.includes('hạ tầng')) return Zap;
    if (name.includes('Nội dung')) return FileText;
    if (name.includes('Giao diện') || name.includes('UI/UX') || name.includes('di động')) return Smartphone;
    return ShieldCheck;
  };

  return (
    <div className="bg-white rounded-3xl p-5 sm:p-7 border-2 border-[#2B1B0E]/15 shadow-sm space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-stone-200 pb-4">
        <div>
          <div className="flex items-center gap-2">
            <h3 className="font-black text-xl text-[#2B1B0E]">
              Kế hoạch hành động toàn diện để vượt mặt đối thủ
            </h3>
            <span
              className={`text-xs font-bold px-2 py-0.5 rounded-full ${
                isAutoGenerated ? 'bg-stone-100 text-stone-600' : 'bg-emerald-100 text-emerald-800'
              }`}
            >
              {isAutoGenerated ? 'Nhận xét tự động' : 'Tư vấn bởi AI'}
            </span>
          </div>
          <p className="text-xs text-stone-500 mt-1">
            Lộ trình tối ưu 15–20 bước cụ thể chia theo 5 nhóm trọng tâm, giúp bạn giữ vững lợi thế cạnh tranh.
          </p>
        </div>
      </div>

      {/* 3 Điều quan trọng nhất cần làm ngay */}
      {topPriorities && topPriorities.length > 0 && (
        <div className="bg-[#FFF3C4] border-2 border-[#FFB400] rounded-2xl p-4 sm:p-5 space-y-3">
          <div className="flex items-center gap-2 font-black text-sm text-[#2B1B0E] uppercase tracking-wider">
            <Star className="w-4 h-4 text-[#8A4B00] fill-[#FFB400]" />
            3 Điều quan trọng nhất cần làm ngay
          </div>
          <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
            {topPriorities.slice(0, 3).map((item, idx) => (
              <div
                key={idx}
                className="bg-white/90 backdrop-blur-sm p-3.5 rounded-xl border border-[#FFB400]/40 shadow-xs space-y-1.5"
              >
                <div className="flex items-center gap-1.5 font-black text-xs text-[#8A4B00]">
                  <span>Ưu tiên #{idx + 1}</span>
                </div>
                <p className="text-xs font-bold text-[#2B1B0E] leading-relaxed">
                  {item}
                </p>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Accordion 5 nhóm khuyến nghị */}
      <div className="space-y-3">
        <div className="text-xs font-bold text-stone-600 uppercase tracking-wider">
          Chi tiết 5 nhóm khuyến nghị hành động:
        </div>

        {detailedRecommendations.map((group, gIdx) => {
          const isOpen = Boolean(openSections[gIdx]);
          const Icon = getCategoryIcon(group.category);

          return (
            <div
              key={gIdx}
              className="border border-[#2B1B0E]/15 rounded-2xl overflow-hidden bg-[#FFFBF0]/50 transition-all"
            >
              <button
                type="button"
                onClick={() => toggleSection(gIdx)}
                className="w-full flex items-center justify-between p-4 bg-white hover:bg-[#FFFBF0] transition-colors text-left cursor-pointer"
              >
                <div className="flex items-center gap-3">
                  <div className="w-8 h-8 rounded-xl bg-[#FFF3C4] text-[#8A4B00] flex items-center justify-center flex-shrink-0">
                    <Icon className="w-4 h-4" />
                  </div>
                  <div>
                    <h4 className="font-bold text-sm text-[#2B1B0E]">
                      {gIdx + 1}. {group.category}
                    </h4>
                    <span className="text-xs text-stone-500 font-medium">
                      {group.items.length} việc cần làm
                    </span>
                  </div>
                </div>
                <div className="p-1 rounded-lg text-stone-400">
                  {isOpen ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
                </div>
              </button>

              {isOpen && (
                <div className="p-4 pt-1 border-t border-stone-100 bg-white/70 space-y-2">
                  {group.items.map((it, itIdx) => (
                    <div
                      key={itIdx}
                      className="flex items-start gap-2.5 p-2.5 rounded-xl bg-[#FFFBF0] border border-[#2B1B0E]/10 text-xs text-[#2B1B0E] leading-relaxed"
                    >
                      <CheckCircle2 className="w-4 h-4 text-[#2E9E5B] flex-shrink-0 mt-0.5" />
                      <span>{it}</span>
                    </div>
                  ))}
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}
